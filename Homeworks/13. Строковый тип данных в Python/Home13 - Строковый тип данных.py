# ============================================================
# Задача 1: Шифр-Приветствие
# Нужно перевести строку в верхний регистр и узнать её длину
# ============================================================

codeword = "начинаю операцию в полночь"   # Исходная строка
upper_codeword = codeword.upper()         # Переводим всю строку в ВЕРХНИЙ РЕГИСТР
length_codeword = len(upper_codeword)     # Считаем количество символов

print(upper_codeword)                     # Выводим строку
print(length_codeword)                    # Выводим её длину


# ============================================================
# Задача 2: Объединение Идентификатора
# Нужно соединить части строки через дефис
# ============================================================

id_parts = ['ID', '2025', 'PYTHON', 'ALPHA']   # Список частей идентификатора
full_id = "-".join(id_parts)                  # Соединяем элементы списка через "-"

print(full_id)                                # Выводим итоговый идентификатор


# ============================================================
# Задача 3: Разделение Файла
# Нужно разбить строку по запятой и взять первый элемент
# ============================================================

file_list = "data.csv,report.pdf,image.png,settings.ini"  # Строка со списком файлов
files = file_list.split(",")                              # Разбиваем строку по ","

print(files[0])                                           # Выводим первый файл


# ============================================================
# Задача 4: Очистка Ввода
# Нужно убрать пробелы и перенос строки, затем проверить строку
# ============================================================

raw_login = " admin_user_2024 \n"    # Логин с пробелами и переносом строки
clean_login = raw_login.strip()     # Убираем все пробельные символы по краям

print(clean_login)                  # Выводим очищенный логин
print(clean_login.isalnum())        # Проверяем: только ли буквы и цифры


# ============================================================
# Задача 5: Извлечение Кода Продукта
# Нужно извлечь 3 символа после второго дефиса
# ============================================================

product_code = "ABC-987-XYZ-45600-DEF"  # Полный код продукта

# Индексы 4,5,6 соответствуют "987"
city_code = product_code[4:7]           # Срез строки

print(city_code)                        # Выводим код города


# ============================================================
# Задача 6: Цензура в Чате
# Нужно заменить слово "редиска" на "***"
# ============================================================

chat_message = "Какая же ты редиска! Совсем не редиска, а молодец."
clean_message = chat_message.replace("редиска", "***")  # Замена всех вхождений

print(clean_message)                                      # Вывод результата


# ============================================================
# Задача 7: Валидация Email (простая)
# Проверяем наличие @ и .
