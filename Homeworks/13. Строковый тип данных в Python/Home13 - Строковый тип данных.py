email = "test@example.com"    # Email-адрес

if "@" in email and "." in email:   # Проверяем оба условия
    print("Email валиден")
else:
    print("Email невалиден")


# ============================================================
# Задача 8: Генератор Пароля
# Нужно перевернуть строку и объединить через @
# ============================================================

base_string = "Secure"                 # Исходная строка
reversed_string = base_string[::-1]    # Переворачиваем строку с помощью среза
password = base_string + "@" + reversed_string  # Объединяем строки

print(password)                        # Выводим пароль


# ============================================================
# Задача 9: Подсчет Слов с Заглавной Буквы
# Нужно посчитать слова, начинающиеся с заглавной буквы
# ============================================================

text = "Петр Первый. Москва Столица. python Язык."

# Заменяем точки на пустоту и разбиваем строку по пробелам
words = text.replace(".", "").split()

count = 0                              # Счетчик слов с заглавной буквы

for word in words:                     # Перебираем каждое слово
    if word.istitle():                 # Проверяем, начинается ли с заглавной буквы
        count += 1                     # Увеличиваем счетчик

print(count)                           # Вывод количества слов


# ============================================================
# Задача 10: Форматирование Даты
# Меняем формат с ДД.ММ.ГГГГ на ГГГГ-ММ-ДД
# ============================================================

date_raw = "15.01.2025"        # Дата в исходном формате

day, month, year = date_raw.split(".")  # Разделяем строку на части
date_formatted = f"{year}-{month}-{day}"  # Собираем новую строку

print(date_formatted)          # Выводим дату в новом формате
