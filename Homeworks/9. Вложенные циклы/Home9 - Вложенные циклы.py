rows = 5                                # Количество строк
triangle = []                           # Будем хранить весь треугольник

for r in range(rows):                   # r — номер строки
    row = [1] * (r + 1)                 # Заполняем строку единицами
    for c in range(1, r):               # Каждая внутренняя ячейка = сумма двух сверху
        row[c] = triangle[r-1][c-1] + triangle[r-1][c]
    triangle.append(row)                # Добавляем строку в список

for row in triangle:                    # Печатаем треугольник
    print(' '.join(map(str, row)))


