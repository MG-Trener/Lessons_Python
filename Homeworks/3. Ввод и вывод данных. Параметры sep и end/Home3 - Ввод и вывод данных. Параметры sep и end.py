# ===== Задача 1: Электронный табель =====
# Используем символ табуляции \t для выравнивания и \n для переноса строки.
# В конце считаем среднюю оценку.

print("\n=== Задача 1: Электронный табель ===")
print("Имя\tКурс\tОценка")

# создаем список студентов (имя, курс, оценка)
students = [
    ("Иванов", "Python", 5),
    ("Петров", "SQL", 4),
    ("Сидоров", "Linux", 3),
    ("Ким", "HTML", 5),
    ("Смирнов", "CSS", 4),
    ("Орлов", "JS", 5),
    ("Егоров", "C++", 3),
    ("Волков", "PHP", 4),
    ("Алиев", "Java", 5),
    ("Каримов", "Go", 4)
]

total = 0
for name, course, grade in students:
    print(f"{name}\t{course}\t{grade}")
    total += grade

avg = total / len(students)
print(f"Средняя оценка:\t\t{avg:.2f}")


