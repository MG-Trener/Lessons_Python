def ternary_task3():
    age = int(input("Возраст: "))
    day = input("День недели: ").lower()
    balance = int(input("Баланс: "))
    vip = input("Есть VIP-браслет? (да/нет): ").lower()
    visits = int(input("Сколько раз был в клубе за месяц: "))

    # Все условия строго тернарниками
    status = (
        "ДОСТУП ЗАПРЕЩЁН: Недостаточно средств" if balance < 5000 else
        "ДОСТУП ЗАПРЕЩЁН: Несовершеннолетний в будний день" if age < 18 and day not in ("пятница", "суббота") else
        "ДОСТУП РАЗРЕШЁН: VIP-зона" if age > 21 and vip == "да" else
        "ДОСТУП РАЗРЕШЁН: Премиум-столик" if visits > 10 and balance > 30000 else
        "ДОСТУП РАЗРЕШЁН: Основной зал (18+)" if age >= 18 else
        "ДОСТУП РАЗРЕШЁН: Зона 16+" if age >= 16 else
        "ДОСТУП РАЗРЕШЁН: Обычный вход" if visits > 5 else
        "ДОСТУП РАЗРЕШЁН: Первый раз -- бесплатный вход!" if visits == 0 else
        "ДОСТУП РАЗРЕШЁН: Добро пожаловать"
    )

    greeting = (
        "Добро пожаловать, легенда Nexus!" if "РАЗРЕШЁН" in status else
        "Приходи с родителями в выходные ;)"
    )

    print("Статус доступа:", status)
    print("Приветствие:", greeting)


