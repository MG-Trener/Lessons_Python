# ---------------------- ЗАДАЧА 1 -----------------------------
# РЕГИСТРАЦИЯ НА МЕЖДУНАРОДНЫЙ ТУРНИР ММА
#
# Правила:
# - Турнир только 18+
# - Справка обязательна
# - Профессионалам нельзя
# - Пол: М или Ж
#
# Категории:
# - 18–20  → юниоры/юниорки
# - 20–35  → взрослые
# - 35+    → ветераны
# ------------------------------------------------------------

def mms_task1():
    age = int(input("Возраст: "))
    sex = input("Пол (М/Ж): ").lower()
    med = input("Есть справка? (да/нет): ").lower()
    pro = input("Профессионал? (да/нет): ").lower()

    if age < 18:
        print("ОТКАЗ: Несовершеннолетний")
        return

    if med != "да":
        print("ОТКАЗ: Нет медицинской справки")
        return

    if pro == "да":
        print("ОТКАЗ: Действующий профессионал")
        return

    if sex not in ("м", "ж"):
        print("ОТКАЗ: Неверно указан пол")
        return

    # Категории
    if 18 <= age <= 20:
        cat = "юниоры" if sex == "м" else "юниорки"
    elif 20 < age < 35:
        cat = "взрослые мужчины" if sex == "м" else "взрослые женщины"
    else:
        cat = "ветераны" if sex == "м" else "ветеранки"

    print(f"ДОПУЩЕН. Категория: {cat}")


# ---------------------- ЗАДАЧА 2 -----------------------------
# ЧЁРНАЯ ПЯТНИЦА — система скидок и бонусов
#
# Полная реализация правил из PDF.
# ------------------------------------------------------------

def discounts_task2():
    total_spent = int(input("Сумма покупок за всё время: "))
    purchase = int(input("Сумма текущей покупки: "))
    loyalty = input("Есть карта лояльности? (да/нет): ").lower()
    invite = input("Приглашение на закрытую распродажу? (да/нет): ").lower()
    black_friday = input("Сегодня Чёрная пятница? (да/нет): ").lower()
    gadget = input("Куплен «Гаджет года»? (да/нет): ").lower()

    # Уровень клиента
    if total_spent >= 500000:
        level = "Platinum"
    elif total_spent >= 200000:
        level = "Gold"
    elif total_spent >= 50000:
        level = "Silver"
    else:
        level = "обычный"

    # Базовая скидка
    if purchase >= 50000:
        discount = 7
    elif purchase >= 30000:
        discount = 5
    elif purchase >= 10000:
        discount = 3
    else:
        discount = 0

    # Особые правила
    if black_friday == "да" and invite == "да":
        discount = 30
        secret = "Закрытая распродажа"
    elif level == "Platinum" and gadget == "да":
        discount = 25
        secret = "Платиновый спецдоступ"
    else:
        secret = "--"

        if level == "Gold" and loyalty == "да":
            discount += 10
        elif level == "Silver" and loyalty == "да":
            discount += 5
        elif loyalty == "да":
            discount += 3

        if black_friday == "да" and invite == "нет":
            discount += 8

        if gadget == "да":
            discount += 5

    # Ограничение на 35%
    if discount > 35:
        discount = 35

    final_sum = int(purchase * (1 - discount / 100))

    # Сертификат
    gift = "Подарочный сертификат 5000 тг" if purchase >= 100000 and discount >= 20 else "--"

    print(f"Сумма без скидки: {purchase} тг")
    print(f"Применённая скидка: {discount}%")
    print(f"Итоговая сумма: {final_sum} тг")
    print(f"Дополнительно: {gift}")
    print(f"Уровень клиента: {level}")
    print(f"Секретный статус: {secret}")


