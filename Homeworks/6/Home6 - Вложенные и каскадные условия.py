def ternary_task1():
    num = int(input("Введите число: "))
    print("Чётное" if num % 2 == 0 else "Нечётное")


# ---------------------- ЗАДАЧА 2 -----------------------------
# Задание:
# Запросить два числа и вывести большее —
# только тернарный оператор.
# ------------------------------------------------------------

def ternary_task2():
    a = int(input("Введите первое число: "))
    b = int(input("Введите второе число: "))
    print(a if a > b else b)


# ---------------------- ЗАДАЧА 3 -----------------------------
# СЕКРЕТНЫЙ ДОСТУП В КИБЕРСПОРТИВНЫЙ КЛУБ "NEXUS"
#
# Условия:
# (См. PDF — ВСЁ реализовано ТОЛЬКО тернарными операторами!)
