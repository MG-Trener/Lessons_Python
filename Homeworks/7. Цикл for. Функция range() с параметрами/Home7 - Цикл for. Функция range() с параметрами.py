def zadanie7():
    print("\nЗадача 7: Числа Фибоначчи")
    print('Напишите программу, которая запрашивает у пользователя число n и выводит первые n \nчисел последовательности Фибоначчи. В этой последовательности каждое следующее \nчисло — это сумма двух предыдущих (начиная с 0 и 1).')
    n = int(input("Сколько чисел вывести? "))
    a, b = 0, 1  # первые два числа Фибоначчи
    for _ in range(n):
        print(a, end=" ")  # вывод текущего числа
        a, b = b, a + b  # обновление пары чисел
    print()

def zadanie8():
    print('Простые числа (тяжелый уровень)')
    print('Напишите программу, которая выводит все простые числа в диапазоне от 2 до 50 \nПростое число — это число, которое делится только на 1 и на само себя.')
    for num in range(2, 51):              # проверяем числа 2...50
        is_prime = True                   # предполагаем что число простое

        for i in range(2, num):           # проверяем делители от 2 до num-1
            if num % i == 0:              # если нашли делитель
                is_prime = False
                break                     # выходим из внутреннего цикла

        if is_prime:
            print(num, end=" | ")

    print()

