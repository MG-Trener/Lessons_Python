# ======================================================
# ЗАДАЧА 9: Матричные индексы (3x3)
# ======================================================

matrix = [                     # Внешний список — строки матрицы
    [                           # Внутренний список — элементы строки
        (i, j)                  # Кортеж: индекс строки i и столбца j
        for j in range(3)       # Перебираем столбцы (0, 1, 2)
    ]
    for i in range(3)           # Перебираем строки (0, 1, 2)
]
print("Задача 9:", matrix)     # Вывод матрицы


# ======================================================
# ЗАДАЧА 10: FizzBuzz (вложенные условия)
# ======================================================

fizzbuzz = [                   # Создаём список результатов
    "FizzBuzz"                 # Если число кратно и 3, и 5
    if x % 3 == 0 and x % 5 == 0
    else "Fizz"                # Если кратно только 3
    if x % 3 == 0
    else "Buzz"                # Если кратно только 5
    if x % 5 == 0
    else x                     # Иначе оставляем само число
    for x in range(1, 16)      # Перебираем числа от 1 до 15
]
print("Задача 10:", fizzbuzz)  # Вывод результата
