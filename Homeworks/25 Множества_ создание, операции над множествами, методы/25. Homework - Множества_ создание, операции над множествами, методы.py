#
# # Задача 8: Анализ участников
# # Есть два мероприятия: "Конференция" и "Воркшоп".
# # 1. Люди, которые участвовали в обоих мероприятиях.
# # 2. Участники только конференции.
# # 3. Полный список уникальных участников.
#
conference = {"Алиса", "Борис", "Катя"}  # участники конференции
workshop = {"Катя", "Дима", "Елена"}     # участники воркшопа

both_events = conference & workshop  # пересечение — участники обоих мероприятий
only_conference = conference - workshop  # разность — только конференция
all_unique = conference | workshop  # объединение — все уникальные участники
#
print("Задача 8")
print("Участвовали в обоих:", both_events)  # вывод участников обоих мероприятий
print("Только конференция:", only_conference)  # вывод только конференции
print("Все участники:", all_unique)  # вывод всех уникальных участников