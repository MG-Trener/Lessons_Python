# Задача 4: «Округли и конвертируй»
# Вам дана цена товара в долларах: price = 12.75.
# Напишите функцию round_price(value), которая округляет число до целого.
# Используя вторую функцию to_tenge(value), которая умножает число на
# текущий курс, выведите итоговую стоимость.

price = 12.75
kurs = 470  # допустим текущий курс 470 тенге за доллар

def round_price(value):
    return round(value)  # round() округляет число

def to_tenge(value):
    return value * kurs  # умножаем на курс

result4 = to_tenge(round_price(price)) # округляем 12.75 до 13 и умножаем на 470
