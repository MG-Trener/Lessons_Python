# Задача 5: «Секретный валидатор»
# Напишите функцию register_user(username). Внутри неё создайте
# вложенную функцию is_valid(), которая проверяет, что имя пользователя
# не короче 3 символов. Если проверка проходит, основная функция должна
# вернуть "Пользователь [имя] зарегистрирован",
# иначе - "Ошибка: короткое имя".

def register_user(username):

    def is_valid():
        return len(username) >= 3  # проверяем длину имени

    if is_valid(): # считаем это True
        return "Пользователь " + username + " зарегистрирован"
    else:
        return "Ошибка: короткое имя"

print("Задача 5:", register_user("Max"))
print("Задача 5:", register_user("Al"))


