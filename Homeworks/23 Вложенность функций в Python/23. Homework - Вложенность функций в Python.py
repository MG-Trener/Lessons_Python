# Задача 1: «Двойное преобразование»
# Напишите две функции: to_upper(text) (делает строку заглавной) и
# add_brackets(text) (заключает строку в квадратные скобки []).
# Вызовите их вложенно, чтобы из строки "python" получить "[PYTHON]".
# Пример вывода: [PYTHON]

def to_upper(text):
    return text.upper()  # метод upper() делает все буквы строки заглавными

def add_brackets(text):
    return "[" + text + "]"  # конкатенация строк (склеивание)

result1 = add_brackets(to_upper("python"))  # вложенный вызов функций
print("Задача 1:", result1)


# Задача 2: «Математическая цепочка»
# Создайте функцию get_square(n), которая возводит число в квадрат, и
# функцию increment(n), которая прибавляет 1.
# Используя вложенный вызов, примените их к числу 4 так, чтобы сначала
# число возвелось в квадрат, а затем к результату прибавилась единица.
# Пример вывода: 17

def get_square(n):
    return n ** 2  # оператор ** возводит число в степень

def increment(n):
    return n + 1  # прибавляем 1

result2 = increment(get_square(4))  # сначала 4*2 = 16, потом +1
print("Задача 2:", result2)


