# Задача 7: «Умный принтер»
# Напишите функцию print_report(title, *data).
# Внутри неё создайте вложенную функцию format_row(item),
# которая добавляет символ • перед каждым элементом.
# Основная функция должна циклом пройтись по data,
# вызывая format_row для каждого элемента,
# и вывести готовый список.
# Пример вывода:
# Отчет по продажам:
# • Молоко
# • Хлеб

def print_report(title, *data):

    def format_row(item):
        return "• " + str(item)  # добавляем маркер

    print(title)
    for item in data:  # перебираем все элементы
        print(format_row(item))  # вызываем вложенную функцию

print("Задача 7:")
print_report("Отчет по продажам:", "Молоко", "Хлеб")


# Задача 8: «Конвертер с проверкой»
# Создайте функцию smart_converter(value).
# Внутри неё напишите вложенную функцию to_cm(inches),
# которая переводит дюймы в сантиметры (умножает на 2.54).
# Основная функция должна проверять:
# если value - это число, то вызывать to_cm и возвращать результат,
# если это строка или другое - возвращать "Некорректный ввод".

def smart_converter(value):

    def to_cm(inches):
        return inches * 2.54  # 1 дюйм = 2.54 см

    if isinstance(value, (int, float)):  # проверяем тип данных
        return to_cm(value)
    else:
        return "Некорректный ввод"

print("Задача 8:", smart_converter(10))
print("Задача 8:", smart_converter("10"))