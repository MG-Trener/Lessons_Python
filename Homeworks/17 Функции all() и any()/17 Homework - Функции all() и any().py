# ------------------------------------------------------------
# ЗАДАЧА 1. Кибербезопасность: проверка сложности пароля
# any() используется, когда достаточно хотя бы одного True
# ------------------------------------------------------------

password = ["p", "a", "s", "s", "1", "2", "!"]
specials = "!@#$%^&*"

# Проверяем: есть ли хотя бы один спецсимвол в пароле
result_1 = any(char in specials for char in password)

print("Задача 1:", result_1)


# ------------------------------------------------------------
# ЗАДАЧА 2. Обработка данных: проверка на пустые значения
# all() используется, когда все условия должны быть True
# ------------------------------------------------------------

row = ["Ivan", "Ivanov", "25", "Astana"]

# Проверяем, что каждая ячейка не является пустой строкой
result_2 = all(cell != "" for cell in row)

print("Задача 2:", result_2)


# ------------------------------------------------------------
# ЗАДАЧА 3. Финансы: поиск подозрительной транзакции
# any() — достаточно одной суммы больше лимита
# ------------------------------------------------------------

payments = [500, 1200, 150000, 300]

# Проверяем, есть ли хотя бы один перевод больше 100 000
result_3 = any(payment > 100_000 for payment in payments)

print("Задача 3:", result_3)


# ------------------------------------------------------------
# ЗАДАЧА 4. Экология: контроль показаний датчиков CO2
# all() — все значения должны быть в норме
# ------------------------------------------------------------

readings = [450, 480, 510, 605, 490]

# Проверяем, что каждое значение меньше 600
result_4 = all(value < 600 for value in readings)

print("Задача 4:", result_4)


# ------------------------------------------------------------
# ЗАДАЧА 5. Социальные сети: модерация комментариев
# any() — если найдено хотя бы одно запрещённое слово
# ------------------------------------------------------------

banned_words = ["спам", "реклама"]
comment = "Это отличная работа, не реклама!"

# Переводим комментарий в нижний регистр для корректного сравнения
result_5 = any(word in comment.lower() for word in banned_words)

print("Задача 5:", result_5)


# ------------------------------------------------------------
# ЗАДАЧА 6. Геймдев: проверка инвентаря героя
# any() — нужен хотя бы один магический предмет
# ------------------------------------------------------------

inventory = ["Sword", "Shield", "Magic Potion", "Bread"]

# Проверяем наличие слова "magic" или "магический" в названии предмета
result_6 = any(
    "magic" in item.lower() or "магический" in item.lower()
    for item in inventory
)

print("Задача 6:", result_6)


# ------------------------------------------------------------
# ЗАДАЧА 7. HR: фильтрация кандидатов
# all() — кандидат должен владеть всеми обязательными навыками
# ------------------------------------------------------------

requirements = ["Python", "SQL", "Git"]
candidate = ["Python", "Git", "C++", "Docker"]

# Проверяем, что каждый обязательный навык есть у кандидата
result_7 = all(skill in candidate for skill in requirements)

print("Задача 7:", result_7)


# ------------------------------------------------------------
# ЗАДАЧА 8. Системное администрирование: поиск опасных файлов
# any() — если найден хотя бы один файл с опасным расширением
# ------------------------------------------------------------

files = ["report.pdf", "vacation.jpg", "virus.exe", "notes.txt"]
dangerous_extensions = [".exe", ".bat", ".sh"]

# Проверяем все файлы на наличие опасных расширений
result_8 = any(
    file.endswith(ext)
    for file in files
    for ext in dangerous_extensions
)

print("Задача 8:", result_8)


# ------------------------------------------------------------
# ЗАДАЧА 9. Логистика: статус доставки заказа
# all() — все товары должны быть доставлены (True)
# ------------------------------------------------------------

order_status = [True, True, False, True]

# all() напрямую проверяет, что все значения равны True
result_9 = all(order_status)

print("Задача 9:", result_9)


# ------------------------------------------------------------
# ЗАДАЧА 10. Сетевые технологии: валидация IP-адреса
# all() — каждый октет должен быть в диапазоне 0–255
# ------------------------------------------------------------

ip_parts = [192, 168, 1, 300]

# Проверяем корректность каждого октета IP-адреса
result_10 = all(0 <= part <= 255 for part in ip_parts)

print("Задача 10:", result_10)
