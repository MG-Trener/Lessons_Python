# Задача 8: «Обработка словаря цен»
# Дан список цен в тенге.
# С помощью map создайте новый список строк,
# где к каждой цене добавлен знак валюты и текст "цена: ".

prices = [1000, 2500, 5000]  # список цен

formatted_prices = list(map(lambda p: f"цена: {p} тг", prices))  # создаем строки с текстом и валютой

print("Задача 8")
print("Форматированные цены:", formatted_prices)  # вывод результата