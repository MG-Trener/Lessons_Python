# Задача 1: «Минуты в секунды»
# Напишите лямбда-функцию, которая принимает количество минут
# и возвращает эквивалент в секундах.

minutes_to_seconds = lambda m: m * 60  # лямбда-функция принимает минуты и переводит их в секунды

print("Задача 1")
print("5 минут =", minutes_to_seconds(5), "секунд")  # вывод результата
print()


# Задача 2: «Абсолютная разность»
# Создайте лямбда-функцию, которая принимает два числа
# и возвращает модуль их разности (используем функцию abs).

abs_diff = lambda a, b: abs(a - b)  # вычисляем модуль разности двух чисел

print("Задача 2")
print("Разность:", abs_diff(10, 25))  # вывод результата
print()


# Задача 3: «Условная лямбда»
# Напишите лямбда-функцию, которая принимает число.
# Если число положительное → "Положительное"
# если отрицательное или ноль → "Не положительное"

check_number = lambda x: "Положительное" if x > 0 else "Не положительное"  # условие внутри лямбды

print("Задача 3")
print("Результат:", check_number(-5))  # проверяем число
print()


# Задача 4: «Сортировка кортежей»
# Дан список кортежей с товарами и ценами.
# Нужно отсортировать по цене (второй элемент кортежа).

items = [("яблоки", 500), ("хлеб", 200), ("сыр", 1200)]  # список товаров и цен

sorted_items = sorted(items, key=lambda item: item[1])  # сортируем по второму элементу кортежа

print("Задача 4")
print("Отсортированный список:", sorted_items)  # вывод результата
print()


# Задача 5: «Только взрослые»
# Дан список возрастов.
# Нужно оставить только тех, кому 18 лет и больше.

ages = [12, 18, 25, 14, 40, 10]  # список возрастов

adults = list(filter(lambda age: age >= 18, ages))  # filter оставляет элементы, которые проходят условие

print("Задача 5")
print("Взрослые:", adults)  # вывод результата
print()


# Задача 6: «Поиск буквы А»
# Дан список городов.
# Нужно оставить только те, которые начинаются на букву "А".

cities = ["Алматы", "Астана", "Шымкент", "Актобе", "Павлодар"]  # список городов

cities_with_a = list(filter(lambda city: city.startswith("А"), cities))  # проверяем первую букву

print("Задача 6")
print("Города на А:", cities_with_a)  # вывод результата
print()


# Задача 7: «Избавляемся от None»
# Дан список со значениями None.
# Нужно удалить все None.

data = [10, None, 20, None, 30, "hello"]  # список с пропусками

clean_data = list(filter(lambda x: x is not None, data))  # оставляем только элементы, которые не None

print("Задача 7")
print("Без None:", clean_data)  # вывод результата
print()


# Задача 8: «Сложный фильтр строк»
# Дан список слов.
# Нужно оставить слова:
# 1) длина больше 3
# 2) содержат букву "a"

words = ["python", "map", "filter", "lambda", "ai", "code"]  # список слов

filtered_words = list(filter(lambda w: len(w) > 3 and "a" in w, words))  # два условия фильтрации

print("Задача 8")
print("Подходящие слова:", filtered_words)  # вывод результата
print()