# ================================
# Задача 8: «Анализ продаж» 📈
# Найти магазин с максимальной выручкой
# ================================

weekly_sales = [
    [10000, 12000, 15000, 8000, 9000, 11000, 14000],
    [5000, 6000, 7000, 5500, 6200, 8000, 9100],
    [20000, 21000, 19000, 25000, 22000, 24000, 26000]
]

max_sum = 0
best_store = 0

for index, sales in enumerate(weekly_sales):
    total = sum(sales)
    if total > max_sum:
        max_sum = total
        best_store = index + 1  # +1, т.к. магазины нумеруются с 1

print("Задача 8: Магазин с максимальной выручкой:", best_store)


