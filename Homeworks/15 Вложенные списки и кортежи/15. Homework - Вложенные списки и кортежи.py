# Задача 6: «Складской учет» 📦
# Проверка наличия товара
# ================================

store = [("яблоки", 100), ("груши", 45), ("апельсины", 80)]

# Ввод товара (для автопроверки можно заменить на конкретное слово)
product_name = input("Введите название товара: ")

found = False  # Флаг, найден ли товар

for product, quantity in store:
    if product == product_name:
        print(f"Количество товара '{product}': {quantity}")
        found = True
        break

if not found:
    print("Товар не найден")


