# Задача 4: Управление очередью печати
# 1) pop() без аргументов — удалить и вывести последний элемент (отменённый документ)
# 2) pop(0) — удалить первый элемент (распечатан) и сохранить в printed_doc
# 3) вывести printed_doc и финальную очередь
print("Задача 4 — управление очередью печати:")
print_queue = ['Отчет', 'Презентация', 'Письмо']  # исходная очередь
cancelled = print_queue.pop()  # удаляем последний элемент (считаем отменённым) и сохраняем его
# после pop() список уменьшился: последний элемент удалён
printed_doc = print_queue.pop(0)  # удаляем первый элемент (распечатан) и сохраняем его
print("  Отменённый документ:", cancelled)
print("  Распечатанный документ (printed_doc):", printed_doc)
print("  Финальная очередь печати:", print_queue)
print()

# Задача 5: Нарушение порядка
# В списке sequence = [1, 2, 4, 6] вставить 3 в правильное место, затем перед 6 вставить 5,
# используя insert() и длину списка.
# Задача 5: Нарушение порядка (обязательные методы: insert(), len())

sequence = [1, 2, 4, 6]  # исходная последовательность
# 1. Вставляем 3 между 2 и 4 — это индекс 2
sequence.insert(2, 3)
# 2. Теперь вставляем 5 перед 6.
#   После вставки 3 список стал: [1, 2, 3, 4, 6]
#   6 стоит на последнем месте => индекс = len(sequence) - 1
index_of_6 = len(sequence) - 1
sequence.insert(index_of_6, 5)
print("Задача 5 — упорядоченный список:", sequence)

# Задача 6: Удаление дубликата
# Описание: в ingredients удалить только первое вхождение "соль" с помощью remove(),
# вывести итоговый список и его длину.
ingredients = ['мука', 'сахар', 'соль', 'вода', 'соль']  # исходный список ингредиентов
ingredients.remove('соль')  # remove удаляет первое вхождение указанного значения
print("Задача 6 — итоговый список ингредиентов (после удаления первого 'соль'):", ingredients)
print("Задача 6 — длина итогового списка:", len(ingredients))
print()

# Задача 7: Смена ведущего
# Описание: поменять местами первого (индекс 0) и последнего (индекс -1) ведущих
hosts = ['Анна', 'Борис', 'Вика', 'Григорий']  # исходный список ведущих
# Меняем местами: используем множественное присваивание (без временной переменной)
hosts[0], hosts[-1] = hosts[-1], hosts[0] # как мы делали a, b = b, a
print("Задача 7 — ведущие после перестановки:", hosts)
print()


# Задача 8: Извлечение средней части
# Описание: из списка символов длины 7 извлечь три центральных элемента (элемент перед центром, центр, элемент после центра)
code = ['C', 'R', 'Y', 'P', 'T', 'O', 'N']  # исходный список символов (длина 7)
center_index = len(code) // 2  # вычисляем центральный индекс; для длины 7 это 3
# срез от (center_index - 1) до (center_index + 2) (правая граница невключительна), получаем 3 элемента
middle_three = code[center_index - 1 : center_index + 2]
print("Задача 8 — центральные три символа:", middle_three)
print()

