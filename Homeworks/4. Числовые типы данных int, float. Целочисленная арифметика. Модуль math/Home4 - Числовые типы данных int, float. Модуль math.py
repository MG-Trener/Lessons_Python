import math  # подключаем модуль math для математических функций

# ===================================================================
# ЗАДАЧА 1: Преобразование секунд в часы и минуты
# Задание:
# Напишите программу, которая запрашивает у пользователя количество
# секунд и преобразует их в формат часов и минут.
# Вывести количество полных часов и оставшихся минут.
# Подсказка: // для часов, % и // для минут.
# ===================================================================

def task1():
    """Преобразование секунд в часы и минуты"""
    seconds = int(input("Введите количество секунд: "))  # ввод секунд
    hours = seconds // 3600                              # полные часы
    minutes = (seconds % 3600) // 60                     # остаток минут (% - остаток от деления)
    print(f"{seconds} секунд = {hours} ч и {minutes} мин\n")


# ===================================================================
# ЗАДАЧА 2: Подсчёт количества полных недель
# Задание:
# Запросите количество дней и посчитайте, сколько полных недель
# и остаток дней можно составить.
# Использовать // и %.
# ===================================================================

def task2():
    """Подсчёт недель и остатка дней"""
    days = int(input("Введите количество дней: "))
    weeks = days // 7           # полные недели
    remaining = days % 7        # остаток дней
    print(f"{days} дней = {weeks} недель и {remaining} дней\n")


