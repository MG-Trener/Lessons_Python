# ЗАДАЧА 10: Площадь и периметр сектора круга
# Задание:
# Пользователь вводит:
#   — радиус r
#   — угол сектора в градусах α
#
# Вычислить:
#   1. Длину дуги: L = 2πr * (α / 360)
#   2. Площадь сектора: S = πr² * (α / 360)
#   3. Периметр сектора: P = 2r + L
# ===================================================================

def task10():
    """Площадь и периметр сектора круга"""
    r = float(input("Введите радиус: "))
    alpha = float(input("Введите угол сектора в градусах: "))

    arc_length = 2 * math.pi * r * (alpha / 360)  # длина дуги
    area = math.pi * r**2 * (alpha / 360)         # площадь сектора
    perimeter = 2 * r + arc_length                # периметр

    print(f"L = {arc_length}")
    print(f"S = {area}")
    print(f"P = {perimeter}\n")


