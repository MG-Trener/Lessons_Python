def task5():
    """Расстояние между двумя точками"""
    print("Введите координаты точки A:")
    x1 = float(input("x1: "))
    y1 = float(input("y1: "))

    print("Введите координаты точки B:")
    x2 = float(input("x2: "))
    y2 = float(input("y2: "))

    distance = math.sqrt((x2 - x1)**2 + (y2 - y1)**2) # возводим в степень
    print(f"Расстояние между точками = {distance}\n")


