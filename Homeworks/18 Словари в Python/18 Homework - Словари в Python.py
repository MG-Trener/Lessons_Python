# ------------------------------------------------------------
# ЗАДАЧА 10. Слияние двух чеков
# ------------------------------------------------------------

# Первый магазин
shop1 = {"Хлеб": 200, "Кефир": 400}

# Второй магазин
shop2 = {"Яблоки": 600, "Хлеб": 210}

# Создаём итоговый словарь
total_bill = {}

# Добавляем все товары из первого магазина
for product, price in shop1.items():
    total_bill[product] = price

# Обрабатываем второй магазин
for product, price in shop2.items():
    # Если товар уже есть в итоговом словаре
    if product in total_bill:
        # Записываем минимальную (выгодную) цену
        total_bill[product] = min(total_bill[product], price)
    else:
        # Если товара не было — просто добавляем
        total_bill[product] = price

# Выводим итоговый чек
print("Задача 10. Итоговый чек:", total_bill)
