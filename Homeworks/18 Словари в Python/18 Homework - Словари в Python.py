# ------------------------------------------------------------
# ЗАДАЧА 1. Контакты в смартфоне
# ------------------------------------------------------------

# Создаём словарь contacts:
# ключ  — имя друга
# значение — номер телефона
contacts = {
    "Али": "+7 777 111 22 33",
    "Дана": "+7 701 333 44 55",
    "Марат": "+7 705 666 77 88"
}
print(contacts)
# Добавляем нового друга в словарь
# Новый ключ автоматически создаётся, если его раньше не было
contacts["Елена"] = "+7 747 999 00 11"
print(contacts)

# Изменяем номер телефона существующего контакта
# Старое значение по ключу "Дана" перезаписывается новым
contacts["Дана"] = "+7 701 000 00 00"

# Удаляем контакт по ключу "Марат"
# del полностью удаляет пару ключ–значение
del contacts["Марат"]

# Выводим только имена контактов
# Метод .keys() возвращает все ключи словаря
print("Задача 1. Контакты:", contacts.keys())


# ------------------------------------------------------------
# ЗАДАЧА 2. Цены на бензин (АЗС КазМунайГаз)
# ------------------------------------------------------------

# Создаём словарь с ценами на топливо
# ключ  — марка бензина
# значение — цена за литр
fuel_prices = {
    "АИ-92": 205,
    "АИ-95": 265,
    "Дизель": 295
}

# Запрашиваем у пользователя марку бензина
# input() всегда возвращает строку
fuel_type = input("Введите марку бензина: ")

# Проверяем, есть ли введённая марка в словаре
if fuel_type in fuel_prices:
    # Если есть — выводим цену по ключу
    print("Цена:", fuel_prices[fuel_type], "тг")
else:
    # Если ключа нет — выводим сообщение об ошибке
    print("Данный вид топлива отсутствует")


# ------------------------------------------------------------
# ЗАДАЧА 3. Переводчик регионов РК
# ------------------------------------------------------------

# Создаём словарь кодов регионов
regions = {
    "01": "Астана",
    "02": "Алматы",
    "13": "Шымкент"
}

# Запрашиваем код региона у пользователя
region_code = input("Введите код региона: ")

# Метод .get() безопасно получает значение по ключу
# Если ключа нет — возвращает None (без ошибки)
city = regions.get(region_code)

# Проверяем, найден ли город
if city:
    # Если найден — выводим город
    print("Город:", city)
else:
    # Если код не найден — выводим сообщение
    print("Регион с таким кодом не найден")


