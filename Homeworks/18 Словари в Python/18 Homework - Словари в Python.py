# ------------------------------------------------------------
# ЗАДАЧА 6. Подсчёт голосов (выборы старосты)
# ------------------------------------------------------------

# Список голосов
votes = ["Али", "Дана", "Али", "Марат", "Дана", "Али", "Елена"]

# Создаём пустой словарь для подсчёта
results = {}

# Перебираем каждое имя в списке голосов
for name in votes:
    # Если имя уже есть в словаре
    if name in results:
        # Увеличиваем счётчик на 1
        results[name] += 1
    else:
        # Если имени ещё нет — создаём и ставим 1 голос
        results[name] = 1

# Выводим результат голосования
print("Задача 6. Голоса:", results)


# ------------------------------------------------------------
# ЗАДАЧА 7. Журнал успеваемости (GPA)
# ------------------------------------------------------------

# Создаём словарь: студент → список оценок
group_grades = {
    "Айбек": [90, 85, 92],
    "Сабина": [78, 80, 88]
}

# Перебираем студентов и их оценки
for student, grades in group_grades.items():
    # Считаем сумму оценок
    total = sum(grades)
    # Считаем количество оценок
    count = len(grades)
    # Вычисляем средний балл
    average = total / count
    # Выводим результат
    print(student, "— средний балл:", average)


# ------------------------------------------------------------
# ЗАДАЧА 8. Склад электроники
# ------------------------------------------------------------

# Создаём словарь склада
stock = {
    "iPhone 15": 10,
    "Samsung S23": 5,
    "MacBook Air": 3
}

# Запрашиваем товар у пользователя
product = input("Введите название товара: ")

# Запрашиваем количество
quantity = int(input("Введите количество: "))

# Проверяем, есть ли товар на складе
if product in stock:
    # Если товара достаточно
    if stock[product] >= quantity:
        # Уменьшаем количество на складе
        stock[product] -= quantity
        print("Продажа успешна")
    else:
        # Если товара меньше, чем нужно
        print("Недостаточно на складе")
else:
    # Если товара вообще нет
    print("Товар отсутствует")


