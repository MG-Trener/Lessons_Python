import math  # Для math.pi, math.floor, math.ceil

# =============================================
# ДОМАШНЕЕ ЗАДАНИЕ: Условные операторы и логика
# =============================================

while True:
    print("\n" + "-" * 40)
    choice = input("Выберите задачу (0–10, 0 = выход): ").strip()

    if choice == "0":
        print("До свидания! Удачи с домашкой! 🚀")
        break

    # Защита от неверного ввода
    if not choice.isdigit() or not 1 <= int(choice) <= 10:
        print("Ошибка: введите число от 1 до 10")
        continue

    choice = int(choice)  # Теперь точно число от 1 до 10

    # ==================================================================
    # Задача 1. Проверка диапазона
    # ==================================================================
    if choice == 1:
        print("\n→ Задача 1: Проверка диапазона")
        num = int(input("   Введите целое число: "))
        if 1 <= num <= 10:
            print("   Входит в диапазон")
        else:
            print("   Не входит")

    # ==================================================================
    # Задача 2. Проверка чётности и положительности
    # ==================================================================
    elif choice == 2:
        print("\n→ Задача 2: Чётное и положительное?")
        num = float(input("   Введите число: "))
        if num > 0 and num % 2 == 0:  # остаток от деления на 2 должен быть равен 0
            print("   Подходит")
        else:
            print("   Не подходит")

    # ==================================================================
    # Задача 3. Проверка пароля с длиной
    # ==================================================================
    elif choice == 3:
        print("\n→ Задача 3: Проверка пароля")
        password = input("   Введите пароль: ").strip()

        if len(password) < 6:
            print("   Причина отказа: пароль слишком короткий (меньше 6 символов)")
        elif password != "python":
            print("   Причина отказа: неверный пароль")
        else:
            print("   Пароль принят")

    # ==================================================================
    # Задача 4. Калькулятор площади круга
    # ==================================================================
    elif choice == 4:
        print("\n→ Задача 4: Площадь круга")
        radius = float(input("   Введите радиус: "))

        if radius < 0:
            print("   Ошибка: радиус не может быть отрицательным")
        elif radius == 0:
            print("   Пустая окружность")
        else:
            area = math.pi * radius ** 2
            print(f"   Площадь круга: {area:.2f}")

    # ==================================================================
    # Задача 5. Конвертер температуры
    # ==================================================================
    elif choice == 5:
        print("\n→ Задача 5: Температура")
        t = float(input("   Введите температуру °C: "))

        if t < 0:
            print("   Лёд")
        elif t < 20:
            print("   Прохладно")
        elif t <= 35:
            print("   Нормально")
        else:
            print("   Жара")

    # ==================================================================
    # Задача 6. Авторизация с ролью
    # ==================================================================
    elif choice == 6:
        print("\n→ Задача 6: Авторизация")
        login = input("   Логин: ").strip()
        password = input("   Пароль: ").strip()
        age = int(input("   Возраст: "))

        if login == "admin" and password == "root" and age >= 18:
            print("   Добро пожаловать, администратор")
        elif login == "user" and age >= 12:
            print("   Здравствуйте, пользователь")
        else:
            print("   Доступ запрещён")

    # ==================================================================
    # Задача 7. Проверка треугольника
    # ==================================================================
    elif choice == 7:
        print("\n→ Задача 7: Существует ли треугольник?")
        a = float(input("   Сторона a: "))
        b = float(input("   Сторона b: "))
        c = float(input("   Сторона c: "))

        if a <= 0 or b <= 0 or c <= 0:
            print("   Ошибка данных")
        elif a + b > c and a + c > b and b + c > a:
            print("   Треугольник существует")
        else:
            print("   Треугольник не может существовать")

    # ==================================================================
    # Задача 8. Калькулятор доставки
    # ==================================================================
    elif choice == 8:
        print("\n→ Задача 8: Стоимость доставки")
        distance = float(input("   Расстояние (км): "))
        weight = float(input("   Вес посылки (кг): "))

        cost = 1000

        if weight > 5:
            cost += 300
        if distance > 20:
            cost += 500
        if weight > 10 and distance > 50:
            cost += 1000
        if weight < 1:
            cost -= 100

        print(f"   Итоговая стоимость: {max(cost, 0)} тг")

    # ==================================================================
    # Задача 9. Калькулятор кредита
    # ==================================================================
    elif choice == 9:
        print("\n→ Задача 9: Одобрение кредита")
        age = int(input("   Возраст: "))
        if age < 18:
            print("   Отказ")
            continue

        income = float(input("   Доход: "))
        if income < 100000:
            print("   Отказ")
            continue

        credit_sum = float(input("   Желаемая сумма: "))
        if credit_sum > income * 10:
            print("   Отказ")
        elif income >= 500000 and credit_sum <= 5_000_000:
            print("   Премиум-одобрение")
        else:
            print("   Кредит одобрен")

    # ==================================================================
    # Задача 10. Классификация чисел
    # ==================================================================
    elif choice == 10:
        print("\n→ Задача 10: Полная классификация числа")
        num = float(input("   Введите число: "))

        # Знак
        if num > 0:
            sign = "положительное"
        elif num < 0:
            sign = "отрицательное"
        else:
            sign = "нулевое"

        # Тип
        type_num = "целое" if num.is_integer() else "дробное"

        # Сравнение с 100
        if num > 100:
            size = "больше 100"
        elif num < 100:
            size = "меньше 100"
        else:
            size = "равно 100"

        # Делимость на 3
        divisible = "делится на 3" if abs(num % 3) < 1e-10 or num == 0 else "не делится на 3"

        # Округления
        r = round(num)
        f = math.floor(num)
        c = math.ceil(num)

        print(f"   Число {num}:")
        print(f"   → {sign}, {type_num}")
        print(f"   → {size}")
        print(f"   → {divisible}")
        print(f"   → round → {r}, floor → {f}, ceil → {c}")

print("\nПрограмма завершена.")